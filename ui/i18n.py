TRANSLATIONS["en"] = ENGLISH


def t(key: str, lang: str = "en") -> str:
    """The string for `key` in `lang`, falling back to English then the key."""
    block = TRANSLATIONS.get(lang)
    if block:
        found = block.get(key)
        if found:
            return found
    return ENGLISH.get(key, key)


def coverage() -> dict[str, int]:
    """Percentage of the interface translated, per language. For the sidebar."""
    total = len(ENGLISH)
    return {code: round(100 * len(set(block) & set(ENGLISH)) / total)
            for code, block in TRANSLATIONS.items()}


def _check() -> None:
    """A key that is not in ENGLISH is a typo, and would silently show as itself."""
    for code, block in TRANSLATIONS.items():
        unknown = set(block) - set(ENGLISH)
        if unknown:
            raise KeyError(
                f"ui/i18n.py: {code} defines keys not in ENGLISH: "
                f"{sorted(unknown)}"
            )


_check()
