"""The interface, in every language Mentora teaches in.

WHY

Mentora could already teach in Hindi — and then wrap that Hindi lesson in an
English chrome: "Start lesson", "Your answer", "Skip question", "Needs work".
A student who picked Hindi because they read Hindi still had to read English
to use the app. That is not multilingual, it is a translated voice-over.

So the language picker now changes the whole interface, on the same click,
with no reload: `t("lesson.answer")` reads st.session_state.ui_lang, and
Streamlit reruns the script top to bottom on every interaction anyway, so the
next frame is drawn in the new language.

ADDING A STRING
Add the key to ENGLISH, then to as many other languages as you can. Anything
missing falls back to English rather than showing a raw key — a screen with
two English words on it is usable; a screen reading `lesson.skip` is not.

ADDING A LANGUAGE
Add it to shared/languages.py first (it needs a voice and a font), then add a
block here. A language with no block here still works: it teaches in that
language and shows an English interface, which is exactly where we started
but now it is the exception rather than the rule.
"""

